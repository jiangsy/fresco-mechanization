    d_wf_utyp Δ2 Γ B ->
    list_disjoint Δ1 Δ2 ->
    d_wf_utyp (Δ1 ++ Δ2) Γ (typ_arrow A B)
| d_wf_utyp__tall : forall L Δ Γ ε A,
    (forall X, X `notin` L ->
       d_wf_utyp Δ ((X ~ dbind_tvar) ++ Γ) (open_typ_wrt_typ A (typ_var_f X))) ->
    ~ List.In ε Δ ->
