(** ** Type consistency Δ | Γ ⊢ T ~ A.
    T is is_utyp; A is is_typ; tags in T marked by Δ are "solved" by this
    judgement. *)
Inductive d_consis :
  list atom -> list (atom * dbind) -> typ -> typ -> Prop :=
| d_consis__unit : forall Γ,
    nil ⨟ Γ ⊨ typ_unit ≈ typ_unit
(* Paper d_consis__var has empty premise; we add binds (the paper's
   implicit wf invariant) so d_consis_preserves_wf goes through
   without a side hypothesis. *)
| d_consis__var : forall Γ X,
    binds X dbind_tvar Γ ->
    nil ⨟ Γ ⊨ (typ_var_f X) ≈ (typ_var_f X)
(* Post-refactor (typ_all_plain removed from typ): LHS shapes are
   {typ_all_etag ε T (tagged-syn), typ_all_col colour_inh T (inh),
   typ_all_col colour_syn T (untagged-syn)}. RHS shapes are
   {typ_all_col colour_inh A, typ_all_col colour_syn A}.

   Paper mapping (declarative.tex Fig 6 / syntax-directed.tex:91–122):
   - __forall_inh_tagged    = EqForallInh, δ=ε case
   - __forall_inh_untagged  = EqForallInh, δ=· case (added 2026-05-17)
   - __forall_syn_tagged    = EqForallSyn, δ=ε case
   - __forall_syn           = EqForallSyn, δ=· case
   - __forall_inh           = structural refl on inh (Coq-only;
                              not in declarative.tex Fig 6)

   Paper rule [EqForallInh] (declarative.tex:946–952) allows the
   potential tag [δ ∈ {·, ε}]; both cases now mechanised. *)
(* Paper [EqForallInh] (declarative.tex:946–952): the δ ∈ {·, ε} cases. *)
| d_consis__forall_inh_tagged : forall L Δ Γ ε T A,
    (forall X, X `notin` L ->
       Δ ⨟ ((X ~ dbind_tvar) ++ Γ) ⊨
         (open_typ_wrt_typ T (typ_var_f X)) ≈
         (open_typ_wrt_typ A (typ_var_f X))) ->
    ~ List.In ε Δ ->
    (ε :: Δ) ⨟ Γ ⊨ (typ_all_etag ε T) ≈ (typ_all_col colour_inh A)
| d_consis__forall_inh_untagged : forall L Δ Γ T A,
    (forall X, X `notin` L ->
       Δ ⨟ ((X ~ dbind_tvar) ++ Γ) ⊨
         (open_typ_wrt_typ T (typ_var_f X)) ≈
         (open_typ_wrt_typ A (typ_var_f X))) ->
    Δ ⨟ Γ ⊨ (typ_all_col colour_syn T) ≈ (typ_all_col colour_inh A)
(* Paper [EqForallSyn] (declarative.tex:954–960): the δ ∈ {·, ε} cases.
   The δ = · case here is [d_consis__forall_syn] below (LHS colour_syn
   → RHS colour_syn structurally). *)
| d_consis__forall_syn_tagged : forall L Δ Γ ε T A,
    (forall X, X `notin` L ->
       Δ ⨟ ((X ~ dbind_tvar) ++ Γ) ⊨
         (open_typ_wrt_typ T (typ_var_f X)) ≈
         (open_typ_wrt_typ A (typ_var_f X))) ->
    Δ ⨟ Γ ⊨ (typ_all_etag ε T) ≈ (typ_all_col colour_syn A)
| d_consis__forall_syn : forall L Δ Γ T A,
    (forall X, X `notin` L ->
       Δ ⨟ ((X ~ dbind_tvar) ++ Γ) ⊨
         (open_typ_wrt_typ T (typ_var_f X)) ≈
         (open_typ_wrt_typ A (typ_var_f X))) ->
    Δ ⨟ Γ ⊨ (typ_all_col colour_syn T) ≈ (typ_all_col colour_syn A)
(* Paper syntax-directed [EqForallInh] (syntax-directed.tex:116–122):
   LHS inh, RHS inh — distinct from declarative Fig 6's [EqForallInh]
   which has LHS syn / RHS inh. *)
| d_consis__forall_inh : forall L Δ Γ T A,
    (forall X, X `notin` L ->
       Δ ⨟ ((X ~ dbind_tvar) ++ Γ) ⊨
         (open_typ_wrt_typ T (typ_var_f X)) ≈
         (open_typ_wrt_typ A (typ_var_f X))) ->
    Δ ⨟ Γ ⊨ (typ_all_col colour_inh T) ≈ (typ_all_col colour_inh A)
(* Arrow: linear-tag semantics (paper writes Δ_1, Δ_2 as set union;
   d_wf_ttyp__arrow enforces disjointness analogously). *)
| d_consis__arrow : forall Δ1 Δ2 Γ T1 T2 A1 A2,
    Δ1 ⨟ Γ ⊨ T1 ≈ A1 ->
    Δ2 ⨟ Γ ⊨ T2 ≈ A2 ->
    list_disjoint Δ1 Δ2 ->
    (Δ1 ++ Δ2) ⨟ Γ ⊨ (typ_arrow T1 T2) ≈ (typ_arrow A1 A2)
where "Δ ⨟ Γ ⊨ T ≈ A" := (d_consis Δ Γ T A) : type_scope.

(** [d_consis_bid]: consistency over the new [bid] inductive (Phase B
    refactor). Mechanical translation of [d_consis] with [typ_*] →
    [bid_*]: each colour-tagged ∀ becomes its own bid constructor, no
    more [colour_syn] / [colour_inh] parameter. Includes the
    [__forall_syn_tagged_both] rule (tagged ≈ tagged) from
    [d_consis_gen] since [bid] allows tagged shapes uniformly. *)
Inductive d_consis_bid :
    list atom -> list (atom * dbind) -> bid -> bid -> Prop :=
| d_consis_bid__unit : forall Γ,
    d_consis_bid nil Γ bid_unit bid_unit
| d_consis_bid__var : forall Γ X,
    binds X dbind_tvar Γ ->
    d_consis_bid nil Γ (bid_var_f X) (bid_var_f X)
(* δ=ε case of EqForallInh: tagged LHS, inh-colour RHS, ε tracked. *)
| d_consis_bid__forall_inh_tagged : forall L Δ Γ ε D D',
    (forall X, X `notin` L ->
       d_consis_bid Δ ((X ~ dbind_tvar) ++ Γ)
         (open_bid_wrt_bid D (bid_var_f X))
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    ~ List.In ε Δ ->
    d_consis_bid (ε :: Δ) Γ (bid_all_etag ε D) (bid_all_inh D')
(* δ=· case of EqForallInh: syn-colour LHS, inh-colour RHS. *)
| d_consis_bid__forall_inh_untagged : forall L Δ Γ D D',
    (forall X, X `notin` L ->
       d_consis_bid Δ ((X ~ dbind_tvar) ++ Γ)
         (open_bid_wrt_bid D (bid_var_f X))
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    d_consis_bid Δ Γ (bid_all_syn D) (bid_all_inh D')
(* δ=ε case of EqForallSyn: tagged LHS, syn-colour RHS. *)
| d_consis_bid__forall_syn_tagged : forall L Δ Γ ε D D',
    (forall X, X `notin` L ->
       d_consis_bid Δ ((X ~ dbind_tvar) ++ Γ)
         (open_bid_wrt_bid D (bid_var_f X))
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    d_consis_bid Δ Γ (bid_all_etag ε D) (bid_all_syn D')
(* δ=ε both sides: tagged ≈ tagged with same ε; needed for refl on
   tagged ph in substitution lemmas. *)
| d_consis_bid__forall_syn_tagged_both : forall L Δ Γ ε D D',
    (forall X, X `notin` L ->
       d_consis_bid Δ ((X ~ dbind_tvar) ++ Γ)
         (open_bid_wrt_bid D (bid_var_f X))
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    d_consis_bid Δ Γ (bid_all_etag ε D) (bid_all_etag ε D')
(* δ=· case of EqForallSyn: syn-colour both sides. *)
| d_consis_bid__forall_syn : forall L Δ Γ D D',
    (forall X, X `notin` L ->
       d_consis_bid Δ ((X ~ dbind_tvar) ++ Γ)
         (open_bid_wrt_bid D (bid_var_f X))
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    d_consis_bid Δ Γ (bid_all_syn D) (bid_all_syn D')
(* Structural refl on inh ∀ (Coq-only; not in declarative.tex Fig 6). *)
| d_consis_bid__forall_inh : forall L Δ Γ D D',
    (forall X, X `notin` L ->
       d_consis_bid Δ ((X ~ dbind_tvar) ++ Γ)
         (open_bid_wrt_bid D (bid_var_f X))
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    d_consis_bid Δ Γ (bid_all_inh D) (bid_all_inh D')
| d_consis_bid__arrow : forall Δ1 Δ2 Γ D1 D2 D1' D2',
    d_consis_bid Δ1 Γ D1 D1' ->
    d_consis_bid Δ2 Γ D2 D2' ->
    list_disjoint Δ1 Δ2 ->
    d_consis_bid (Δ1 ++ Δ2) Γ (bid_arrow D1 D2) (bid_arrow D1' D2').

(** ** Type subtyping Γ ⊢_M^Δ T ≤ A. *)
Inductive d_sub :
  mode -> list atom -> list (atom * dbind) -> typ -> typ -> Prop :=
| d_sub__infer : forall Γ T A,
    (* paper Infer: typsub TI · Γ syn{T} syn{A} — [T] and [A] are
       colourless bases, each painted [syn] (their only colour). *)
    nil ⨟ Γ ⊨ (syn_color T) ≈ (syn_color A) ->
    Γ ⊢[ mode_ti ; nil ] (syn_color T) ⊑ (syn_color A)
| d_sub__check : forall Δ Γ T A,
    (* paper Check: typsub TC Δ Γ syn{T} inh{A} — base [T] painted
       [syn] (and guarded), base [A] painted [inh]. *)
    guarded_typ (syn_color T) ->
    Δ ⨟ Γ ⊨ (syn_color T) ≈ (inh_color A) ->
    Γ ⊢[ mode_tc ; Δ ] (syn_color T) ⊑ (inh_color A)
| d_sub__forall_r : forall L Δ Γ T A,
    (forall X, X `notin` L ->
       ((X ~ dbind_tvar) ++ Γ) ⊢[ mode_tc ; Δ ] T ⊑ (open_typ_wrt_typ A (typ_var_f X))) ->
    Γ ⊢[ mode_tc ; Δ ] T ⊑ (typ_all_col colour_inh A)
| d_sub__arg : forall Δ1 Δ2 Γ m T1 T2 A1 A2,
    Δ1 ⨟ Γ ⊨ T1 ≈ A1 ->
    Γ ⊢[ m ; Δ2 ] T2 ⊑ A2 ->
    Γ ⊢[ mode_fn m ; (Δ1 ++ Δ2) ] (typ_arrow T1 T2) ⊑ (typ_arrow A1 A2)
| d_sub__forall_l_tagged : forall Δ Δ' Γ m ε T ph A,
    m <> mode_ti ->
    list_disjoint Δ' Δ ->
    Δ' ⨟ Γ ⊢ₜₜ ph ->
    Γ ⊢[ m ; (Δ ++ Δ') ] (open_typ_wrt_typ T ph) ⊑ A ->
    Γ ⊢[ m ; Δ ] (typ_all_etag ε T) ⊑ A
(* Paper [sublab{ForallL}] (declarative.tex:923–930) allows the potential
   tag [δ ∈ {·, ε}]. The [δ = ε] case is [d_sub__forall_l_tagged] above.
   The [δ = ·] case is [d_sub__forall_l_untagged] below: the LHS is an
   untagged-syn ∀ encoded as [typ_all_col colour_syn T]; no ε to track.
   See [docs/superpowers/specs/2026-05-17-delta-encoding-refactor-design.md]. *)
| d_sub__forall_l_untagged : forall Δ Δ' Γ m T ph A,
    m <> mode_ti ->
    list_disjoint Δ' Δ ->
    Δ' ⨟ Γ ⊢ₜₜ ph ->
    Γ ⊢[ m ; (Δ ++ Δ') ] (open_typ_wrt_typ T ph) ⊑ A ->
    Γ ⊢[ m ; Δ ] (typ_all_col colour_syn T) ⊑ A
where "Γ ⊢[ M ; Δ ] T ⊑ A" := (d_sub M Δ Γ T A) : type_scope.

(** [d_sub_bid]: subtyping over the new [bid] inductive (Phase B
    refactor). Mechanical translation of [d_sub] with [typ_*] →
    [bid_*], plus the BROADENED __infer / __check rules: the LHS is
    [utyp] (paper's syn{∀^δ}, admits both colour_syn and ε-tagged ∀),
    the RHS is [bid] plus a structural predicate ([is_syn] for
    __infer, [is_inh] for __check). This removes the spurious
    [d_wf_typ Γ T] premise B.3's __infer case needed in the
    typ-based formulation.

    The utyp LHS is coerced to bid via [utyp_to_bid] (implicit). *)
Inductive d_sub_bid :
  mode -> list atom -> list (atom * dbind) -> bid -> bid -> Prop :=
| d_sub_bid__infer : forall Γ (F : utyp) (D : bid),
    d_consis_bid nil Γ F D ->
    is_syn D ->
    d_sub_bid mode_ti nil Γ F D
| d_sub_bid__check : forall Δ Γ (F : utyp) (D : bid),
    (* TODO: guarded_typ analogue over utyp / bid — placeholder for
       now (omit guardedness; restore once we have guarded_bid). *)
    d_consis_bid Δ Γ F D ->
    is_inh D ->
    d_sub_bid mode_tc Δ Γ F D
| d_sub_bid__forall_r : forall L Δ Γ D D',
    (forall X, X `notin` L ->
       d_sub_bid mode_tc Δ ((X ~ dbind_tvar) ++ Γ) D
         (open_bid_wrt_bid D' (bid_var_f X))) ->
    d_sub_bid mode_tc Δ Γ D (bid_all_inh D')
| d_sub_bid__arg : forall Δ1 Δ2 Γ m D1 D2 D1' D2',
    d_consis_bid Δ1 Γ D1 D1' ->
    d_sub_bid m Δ2 Γ D2 D2' ->
    d_sub_bid (mode_fn m) (Δ1 ++ Δ2) Γ (bid_arrow D1 D2) (bid_arrow D1' D2')
| d_sub_bid__forall_l_tagged : forall Δ Δ' Γ m ε D ph D',
    m <> mode_ti ->
    list_disjoint Δ' Δ ->
    (* ph is a utyp with is_ttyp_utyp; embedded as bid via coercion.
       For now we keep ph : utyp and require is_ttyp_utyp. *)
    is_ttyp_utyp ph ->
    d_sub_bid m (Δ ++ Δ') Γ (open_bid_wrt_bid D (utyp_to_bid ph)) D' ->
    d_sub_bid m Δ Γ (bid_all_etag ε D) D'
| d_sub_bid__forall_l_untagged : forall Δ Δ' Γ m D ph D',
    m <> mode_ti ->
    list_disjoint Δ' Δ ->
    is_ttyp_utyp ph ->
    d_sub_bid m (Δ ++ Δ') Γ (open_bid_wrt_bid D (utyp_to_bid ph)) D' ->
    d_sub_bid m Δ Γ (bid_all_syn D) D'.

