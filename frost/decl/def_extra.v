(** ** Declarative typing Γ ⊢[ M ] e ⇒ A and skeleton inference Γ ⊢[ M ] e ⇨ P.
    These two are genuinely mutual due to the App rule (d_typing__app reads
    the argument's skeleton via d_pat, and d_pat__app reads the function's
    type via d_typing). The four upstream judgments d_refine_syn / d_refine
    / d_pat_consis / d_pat_sub are *not* mutual with these — see the
    standalone Inductives above. *)
Inductive d_typing :
  mode -> list (atom * dbind) -> exp -> typ -> Prop :=
| d_typing__unit : forall Γ,
    mode_typ_compat mode_ti typ_unit ->
    d_typing mode_ti Γ exp_unit typ_unit
| d_typing__var : forall Γ x A,
    (* paper Var: Γ ∋ x : syn{A} ⟹ x : syn{A} — context binding and
       conclusion are the SAME colour (syn), hence the same term [A].
       [A] is already a [syn]-painting (a context invariant maintained
       by __abs / __abs_anno binding [syn_color _]); this rule just
       reads it back, so no painting is applied here. *)
    binds x (dbind_typ A) Γ ->
    d_typing mode_ti Γ (exp_var_f x) A
| d_typing__anno : forall Γ e A,
    (* paper Anno: M : inh{A} ⟹ (M : inh{A}) : syn{A} — one colourless
       base [A : ctyp]: the premise + term annotation are its [inh]
       painting, the conclusion its [syn] painting. The term carries
       [inh_color A] (a [typ]); [A : ctyp] never enters [exp]. *)
    d_typing mode_tc Γ e (inh_color A) ->
    d_typing mode_ti Γ (exp_anno e (inh_color A)) (syn_color A)
| d_typing__sub : forall Γ m e A B,
    is_base_term e ->
    d_typing mode_ti Γ e A ->
    d_sub m nil Γ A B ->
    d_typing m Γ e B
| d_typing__freeze : forall Γ e A,
    d_typing mode_ti Γ e A ->
    d_typing mode_tc Γ (exp_freeze e) A
| d_typing__forall : forall L Γ e A,
    is_value e ->
    (forall X, X `notin` L ->
       d_typing mode_tc ((X ~ dbind_tvar) ++ Γ) e
         (open_typ_wrt_typ A (typ_var_f X))) ->
    d_typing mode_tc Γ e (typ_all_col colour_inh A)
| d_typing__abs : forall L Γ m e A B,
    (* paper Abs: Γ,x:syn{A} ⊢ M:B ⟹ λx.M : inh{A}→B — one colourless
       base [A]: the context binding is its [syn] painting, the
       conclusion's arrow-arg its [inh] painting. *)
    d_wf_typ Γ (inh_color A) ->
    (forall x, x `notin` L ->
       d_typing (decr_mode m) ((x ~ dbind_typ (syn_color A)) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) B) ->
    d_typing m Γ (exp_abs e) (typ_arrow (inh_color A) B)
| d_typing__abs_anno : forall L Γ m e A B,
    (* paper AbsAnno: Γ,x:syn{A} ⊢ M:B ⟹ λx^{inh A}.M : syn{A}→B — one
       colourless base [A : ctyp]: the context binding AND conclusion
       arrow-arg are its [syn] painting (same colour ⟹ same term); the
       term carries [inh_color A] (a [typ]) — the paper's [inh A]
       annotation; [A : ctyp] never enters [exp]. *)
    d_wf_typ Γ (syn_color A) ->
    (forall x, x `notin` L ->
       d_typing (decr_mode m) ((x ~ dbind_typ (syn_color A)) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) B) ->
    d_typing m Γ (exp_abs_anno (inh_color A) e) (typ_arrow (syn_color A) B)
| d_typing__app : forall Γ m e1 e2 P P' B,
    (* paper App: pati N syn{P} ⟹ inh{P} ⇝ bid{A} ⟹
       M : bid{A}→bid{B} ⟹ N : inh{A} ⟹ (M N) : bid{B}.
       One colourless skeleton base [P : ctyp]: [d_pat] reads its
       [syn] painting, [d_refine_syn] its [inh] painting. The
       refinement output [P' : typ] IS the function's argument type
       ([bid{A}]); the argument is checked at [inh{A}], the [inh]
       painting of [P']'s erasure: [inh_color (erase P')]. *)
    d_pat mode_tc Γ e2 (syn_color P) ->
    d_refine_syn nil Γ (inh_color P) P' ->
    d_typing (mode_fn m) Γ e1 (typ_arrow P' B) ->
    d_typing mode_tc Γ e2 (inh_color (erase P')) ->
    d_typing m Γ (exp_app e1 e2) B

with d_pat :
  mode -> list (atom * dbind) -> exp -> typ -> Prop :=
| d_pat__unit : forall Γ,
    d_pat mode_ti Γ exp_unit typ_unit
| d_pat__var : forall Γ x P,
    binds x (dbind_skel P) Γ ->
    d_pat mode_ti Γ (exp_var_f x) P
| d_pat__anno : forall Γ e A,
    d_wf_typ Γ A ->
    d_pat mode_ti Γ (exp_anno e A) A
| d_pat__sub : forall Γ m e P Q,
    is_base_term e ->
    d_pat mode_ti Γ e P ->
    d_pat_sub m nil Γ P Q ->
    d_pat m Γ e Q
| d_pat__freeze : forall Γ e P,
    d_pat mode_ti Γ e P ->
    d_pat mode_tc Γ (exp_freeze e) P
| d_pat__abs : forall L Γ m e P Q,
    m <> mode_tc ->
    is_inh_skel P ->
    d_wf_skel nil Γ P ->
    (forall x, x `notin` L ->
       d_pat (decr_mode m) ((x ~ dbind_skel P) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat m Γ (exp_abs e) (typ_arrow P Q)
| d_pat__abs_check : forall L Γ e Q,
    (forall x, x `notin` L ->
       d_pat mode_tc ((x ~ dbind_skel typ_hole) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat mode_tc Γ (exp_abs e) (typ_tophole (typ_arrow typ_hole Q))
| d_pat__abs_anno : forall L Γ m e A Q,
    m <> mode_tc ->
    d_wf_typ Γ A ->
    (forall x, x `notin` L ->
       d_pat (decr_mode m) ((x ~ dbind_typ A) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat m Γ (exp_abs_anno A e) (typ_arrow A Q)
| d_pat__abs_anno_check : forall L Γ e A Q,
    d_wf_typ Γ A ->
    (forall x, x `notin` L ->
       d_pat mode_tc ((x ~ dbind_typ A) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat mode_tc Γ (exp_abs_anno A e) (typ_tophole (typ_arrow A Q))
| d_pat__app : forall Γ m e1 e2 P P' Q,
    (* paper App (pattern side): one colourless skeleton base [P];
       [d_pat] reads its [syn] painting, [d_refine_syn] its [inh]
       painting; [P'] is the refinement output / function arg. *)
    d_pat mode_tc Γ e2 (syn_color P) ->
    d_refine_syn nil Γ (inh_color P) P' ->
    d_typing (mode_fn m) Γ e1 (typ_arrow P' Q) ->
    d_pat m Γ (exp_app e1 e2) Q
.

(* ===================================================================== *)
(*  Phase C.0 — bid-typed typing + pat mutual block. Mirrors the legacy  *)
(*  [d_typing] / [d_pat] over the new type hierarchy, with these         *)
(*  deliberate departures from a literal 1:1 mirror:                     *)
(*    - typ result → bid result; pat result → skel.                      *)
(*    - exp_anno / exp_abs_anno annotation argument → ptyp (colourless;  *)
(*      painted into bid via [ptyp_to_bid_syn] / [ptyp_to_bid_inh] in    *)
(*      the rule body, mirroring the paper's syn{·} / inh{·} story).     *)
(*    - sub / refine_syn / pat_sub premises route through the _bid /     *)
(*      _skel versions ([d_sub_bid], [d_refine_syn_skel],                *)
(*      [d_pat_sub_skel]).                                               *)
(*    - dbind_typ argument still carries [typ] for now — the dbind       *)
(*      constructor lives in def_ott.v and changing it would cascade     *)
(*      into algo. Bid-aware binding is reconstructed at lookup via      *)
(*      [ctyp_to_bid_syn (erase _)]. Phase E introduces a dbind variant. *)
(*    - [d_pat_bid__abs] hard-excludes [skel_hole] / [skel_tophole] /    *)
(*      [skel_all_syn] / [skel_all_etag] via inequality premises (rather *)
(*      than admitting them through a generic [is_inh_skel] as the       *)
(*      legacy [d_pat__abs] does); the hole-output and tophole cases     *)
(*      are covered by the dedicated [d_pat_bid__abs_check] /            *)
(*      [d_pat_bid__abs_anno_check] rules.                               *)
(* ===================================================================== *)

Inductive d_typing_bid :
  mode -> list (atom * dbind) -> exp -> bid -> Prop :=
| d_typing_bid__unit : forall Γ,
    (* The [mode_typ_compat mode_ti typ_unit] premise is trivially true
       (mode_ti always matches concrete types). Retained verbatim from
       the legacy [d_typing__unit] as a porting placeholder; collapses
       to a pure unit-introduction once a [mode_bid_compat] over [bid]
       lands. *)
    mode_typ_compat mode_ti typ_unit ->
    d_typing_bid mode_ti Γ exp_unit bid_unit
| d_typing_bid__var : forall Γ x A,
    binds x (dbind_typ A) Γ ->
    d_typing_bid mode_ti Γ (exp_var_f x) (ctyp_to_bid_syn (erase A))
| d_typing_bid__anno : forall Γ e (N : ptyp),
    d_typing_bid mode_tc Γ e (ptyp_to_bid_inh N) ->
    d_typing_bid mode_ti Γ (exp_anno e (inh_color (ptyp_to_ctyp N)))
                          (ptyp_to_bid_syn N)
| d_typing_bid__sub : forall Γ m e A B,
    is_base_term e ->
    d_typing_bid mode_ti Γ e A ->
    d_sub_bid m nil Γ A B ->
    d_typing_bid m Γ e B
| d_typing_bid__freeze : forall Γ e A,
    d_typing_bid mode_ti Γ e A ->
    d_typing_bid mode_tc Γ (exp_freeze e) A
| d_typing_bid__forall : forall L Γ e D,
    is_value e ->
    (forall X, X `notin` L ->
       d_typing_bid mode_tc ((X ~ dbind_tvar) ++ Γ) e
         (open_bid_wrt_bid D (bid_var_f X))) ->
    d_typing_bid mode_tc Γ e (bid_all_inh D)
| d_typing_bid__abs : forall L Γ m e (N : ptyp) B,
    d_wf_bid Γ (ptyp_to_bid_inh N) ->
    (forall x, x `notin` L ->
       d_typing_bid (decr_mode m) ((x ~ dbind_typ (syn_color (ptyp_to_ctyp N))) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) B) ->
    d_typing_bid m Γ (exp_abs e) (bid_arrow (ptyp_to_bid_inh N) B)
| d_typing_bid__abs_anno : forall L Γ m e (N : ptyp) B,
    d_wf_bid Γ (ptyp_to_bid_syn N) ->
    (forall x, x `notin` L ->
       d_typing_bid (decr_mode m) ((x ~ dbind_typ (syn_color (ptyp_to_ctyp N))) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) B) ->
    d_typing_bid m Γ (exp_abs_anno (inh_color (ptyp_to_ctyp N)) e)
                     (bid_arrow (ptyp_to_bid_syn N) B)
| d_typing_bid__app : forall Γ m e1 e2 (P : ctyp) P' B,
    d_pat_bid mode_tc Γ e2 (ctyp_to_skel P) ->
    d_refine_syn_skel nil Γ (ctyp_to_skel P) P' ->
    d_typing_bid (mode_fn m) Γ e1 (bid_arrow (ctyp_to_bid_inh (skel_to_ctyp P')) B) ->
    d_typing_bid mode_tc Γ e2 (ctyp_to_bid_inh (skel_to_ctyp P')) ->
    d_typing_bid m Γ (exp_app e1 e2) B

with d_pat_bid :
  mode -> list (atom * dbind) -> exp -> skel -> Prop :=
| d_pat_bid__unit : forall Γ,
    d_pat_bid mode_ti Γ exp_unit skel_unit
| d_pat_bid__var : forall Γ x P,
    binds x (dbind_skel P) Γ ->
    d_pat_bid mode_ti Γ (exp_var_f x) (ctyp_to_skel (erase P))
| d_pat_bid__anno : forall Γ e (N : ptyp),
    d_wf_bid Γ (ptyp_to_bid_syn N) ->
    d_pat_bid mode_ti Γ (exp_anno e (inh_color (ptyp_to_ctyp N)))
                        (ctyp_to_skel (ptyp_to_ctyp N))
| d_pat_bid__sub : forall Γ m e P Q,
    is_base_term e ->
    d_pat_bid mode_ti Γ e P ->
    d_pat_sub_skel m nil Γ P Q ->
    d_pat_bid m Γ e Q
| d_pat_bid__freeze : forall Γ e P,
    d_pat_bid mode_ti Γ e P ->
    d_pat_bid mode_tc Γ (exp_freeze e) P
| d_pat_bid__abs : forall L Γ m e P Q,
    m <> mode_tc ->
    (forall R, P <> skel_all_syn R) ->
    (forall ε R, P <> skel_all_etag ε R) ->
    P <> skel_hole ->
    (forall R, P <> skel_tophole R) ->
    d_wf_skel_new nil Γ P ->
    (forall x, x `notin` L ->
       d_pat_bid (decr_mode m) ((x ~ dbind_skel (erase_skel_to_typ P)) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat_bid m Γ (exp_abs e) (skel_arrow P Q)
| d_pat_bid__abs_check : forall L Γ e Q,
    (forall x, x `notin` L ->
       d_pat_bid mode_tc ((x ~ dbind_skel typ_hole) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat_bid mode_tc Γ (exp_abs e) (skel_tophole (skel_arrow skel_hole Q))
| d_pat_bid__abs_anno : forall L Γ m e (N : ptyp) Q,
    m <> mode_tc ->
    d_wf_bid Γ (ptyp_to_bid_syn N) ->
    (forall x, x `notin` L ->
       d_pat_bid (decr_mode m) ((x ~ dbind_typ (inh_color (ptyp_to_ctyp N))) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat_bid m Γ (exp_abs_anno (inh_color (ptyp_to_ctyp N)) e)
                  (skel_arrow (ctyp_to_skel (ptyp_to_ctyp N)) Q)
| d_pat_bid__abs_anno_check : forall L Γ e (N : ptyp) Q,
    d_wf_bid Γ (ptyp_to_bid_syn N) ->
    (forall x, x `notin` L ->
       d_pat_bid mode_tc ((x ~ dbind_typ (inh_color (ptyp_to_ctyp N))) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) Q) ->
    d_pat_bid mode_tc Γ (exp_abs_anno (inh_color (ptyp_to_ctyp N)) e)
                        (skel_tophole (skel_arrow (ctyp_to_skel (ptyp_to_ctyp N)) Q))
| d_pat_bid__app : forall Γ m e1 e2 (P : ctyp) P' (Q : skel),
    (* Note: [Q] is the pat output (skel); the function's return is the
       bid lifting [ctyp_to_bid_inh (skel_to_ctyp Q)] of that skel. The
       skel→bid bridge here parallels [d_typing_bid__app]'s arg side. *)
    d_pat_bid mode_tc Γ e2 (ctyp_to_skel P) ->
    d_refine_syn_skel nil Γ (ctyp_to_skel P) P' ->
    d_typing_bid (mode_fn m) Γ e1
      (bid_arrow (ctyp_to_bid_inh (skel_to_ctyp P'))
                 (ctyp_to_bid_inh (skel_to_ctyp Q))) ->
    d_pat_bid m Γ (exp_app e1 e2) Q
.

(** ** Syntax-directed declarative typing (paper syntax-directed.tex:454+).

    Difference from [d_typing]:
    - REMOVES [d_typing__forall] (the value-restriction rule that lifts a
      value to a typ_all_col colour_inh).
    - ADDS [ds_typing__abs_forall] and [ds_typing__abs_anno_forall]:
      these absorb the forall introduction directly into the abstraction
      rule, producing [typ_all_col colour_inh (typ_arrow A B)] in one step.

    This is the system the paper uses to prove [General Subsumption] (D1)
    without the body-conversion cycle that blocks the direct bidirectional
    proof.

    Single-forall encoding here. Multi-forall (paper's [∀ᾱ.A→B] with ᾱ a
    sequence) is approximated by iterated application — sufficient for our
    target uses (D1 closure). See [TODO: multi-forall list-binder version]
    if a fuller treatment becomes necessary.

    Note: [ds_typing] is mutual with the ORIGINAL [d_pat] (the d_pat
    judgment doesn't change in the syntax-directed system). Mechanized
    here as a standalone inductive that REUSES [d_pat], [d_sub], etc.
    from the bidirectional development. *)
Inductive ds_typing :
  mode -> list (atom * dbind) -> exp -> typ -> Prop :=
| ds_typing__unit : forall Γ,
    ds_typing mode_ti Γ exp_unit typ_unit
| ds_typing__var : forall Γ x A,
    binds x (dbind_typ A) Γ ->
    ds_typing mode_ti Γ (exp_var_f x) A
| ds_typing__anno : forall Γ e A,
    is_inh_typ A ->
    ds_typing mode_tc Γ e A ->
    ds_typing mode_ti Γ (exp_anno e A) A
| ds_typing__sub : forall Γ m e A B,
    is_base_term e ->
    ds_typing mode_ti Γ e A ->
    d_sub m nil Γ A B ->
    ds_typing m Γ e B
| ds_typing__freeze : forall Γ e A,
    ds_typing mode_ti Γ e A ->
    ds_typing mode_tc Γ (exp_freeze e) A
(* NO __forall rule: absorbed into __abs_forall / __abs_anno_forall below *)
| ds_typing__abs : forall L Γ m e A B,
    is_inh_typ A ->
    d_wf_typ Γ A ->
    (forall x, x `notin` L ->
       ds_typing (decr_mode m) ((x ~ dbind_typ A) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) B) ->
    ds_typing m Γ (exp_abs e) (typ_arrow A B)
| ds_typing__abs_forall : forall L Γ e A B,
    (* paper's AbsForall with single-α (multi-α via iteration if needed).
       Note: A and B are in body form (may have typ_var_b 0 for α). *)
    (forall α, α `notin` L ->
       is_inh_typ (open_typ_wrt_typ A (typ_var_f α))) ->
    (forall α, α `notin` L ->
       d_wf_typ ((α ~ dbind_tvar) ++ Γ) (open_typ_wrt_typ A (typ_var_f α))) ->
    (forall α x, α `notin` L -> x `notin` (L `union` singleton α) ->
       ds_typing mode_tc
         ((x ~ dbind_typ (open_typ_wrt_typ A (typ_var_f α)))
          ++ (α ~ dbind_tvar) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x))
         (open_typ_wrt_typ B (typ_var_f α))) ->
    ds_typing mode_tc Γ (exp_abs e)
              (typ_all_col colour_inh (typ_arrow A B))
| ds_typing__abs_anno : forall L Γ m e A B,
    d_wf_typ Γ A ->
    (forall x, x `notin` L ->
       ds_typing (decr_mode m) ((x ~ dbind_typ A) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x)) B) ->
    ds_typing m Γ (exp_abs_anno A e) (typ_arrow A B)
| ds_typing__abs_anno_forall : forall L Γ e A B,
    (forall α, α `notin` L ->
       d_wf_typ ((α ~ dbind_tvar) ++ Γ) (open_typ_wrt_typ A (typ_var_f α))) ->
    (forall α x, α `notin` L -> x `notin` (L `union` singleton α) ->
       ds_typing mode_tc
         ((x ~ dbind_typ (open_typ_wrt_typ A (typ_var_f α)))
          ++ (α ~ dbind_tvar) ++ Γ)
         (open_exp_wrt_exp e (exp_var_f x))
         (open_typ_wrt_typ B (typ_var_f α))) ->
    ds_typing mode_tc Γ (exp_abs_anno A e)
              (typ_all_col colour_inh (typ_arrow A B))
| ds_typing__app : forall Γ m e1 e2 P P' A B,
    d_pat mode_tc Γ e2 P ->
    d_refine_syn nil Γ P P' ->
    ds_typing (mode_fn m) Γ e1 (typ_arrow A B) ->
    ds_typing mode_tc Γ e2 A ->
    ds_typing m Γ (exp_app e1 e2) B
.
