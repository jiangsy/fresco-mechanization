(** [d_wf_bid]: structural wf over [bid]. Admits all three ∀ forms
    (colour_syn, colour_inh, ε-tagged). Linearity of ε tags is tracked
    separately (cf. [d_wf_ttyp] for the old typ-based version). *)
Inductive d_wf_bid : list (atom * dbind) -> bid -> Prop :=
| d_wf_bid__unit : forall Γ,
    d_wf_bid Γ bid_unit
| d_wf_bid__var : forall Γ X,
    binds X dbind_tvar Γ ->
    d_wf_bid Γ (bid_var_f X)
| d_wf_bid__arrow : forall Γ D1 D2,
    d_wf_bid Γ D1 ->
    d_wf_bid Γ D2 ->
    d_wf_bid Γ (bid_arrow D1 D2)
| d_wf_bid__all_syn : forall L Γ D,
    (forall X, X `notin` L ->
       d_wf_bid ((X ~ dbind_tvar) ++ Γ) (open_bid_wrt_bid D (bid_var_f X))) ->
    d_wf_bid Γ (bid_all_syn D)
| d_wf_bid__all_inh : forall L Γ D,
    (forall X, X `notin` L ->
       d_wf_bid ((X ~ dbind_tvar) ++ Γ) (open_bid_wrt_bid D (bid_var_f X))) ->
    d_wf_bid Γ (bid_all_inh D)
| d_wf_bid__all_etag : forall L Γ ε D,
    (forall X, X `notin` L ->
       d_wf_bid ((X ~ dbind_tvar) ++ Γ) (open_bid_wrt_bid D (bid_var_f X))) ->
    d_wf_bid Γ (bid_all_etag ε D).

(** [d_wf_utyp_new]: structural wf over [utyp]. (The legacy
    [d_wf_utyp] over [typ] retains its name until Phase F.) Admits
    colour_syn and ε-tagged ∀; no colour_inh by construction of [utyp]. *)
Inductive d_wf_utyp_new : list (atom * dbind) -> utyp -> Prop :=
| d_wf_utyp_new__unit : forall Γ,
    d_wf_utyp_new Γ utyp_unit
| d_wf_utyp_new__var : forall Γ X,
    binds X dbind_tvar Γ ->
    d_wf_utyp_new Γ (utyp_var_f X)
| d_wf_utyp_new__arrow : forall Γ F1 F2,
    d_wf_utyp_new Γ F1 ->
    d_wf_utyp_new Γ F2 ->
    d_wf_utyp_new Γ (utyp_arrow F1 F2)
| d_wf_utyp_new__all_syn : forall L Γ F,
    (forall X, X `notin` L ->
       d_wf_utyp_new ((X ~ dbind_tvar) ++ Γ) (open_utyp_wrt_utyp F (utyp_var_f X))) ->
    d_wf_utyp_new Γ (utyp_all_syn F)
| d_wf_utyp_new__all_etag : forall L Γ ε F,
    (forall X, X `notin` L ->
       d_wf_utyp_new ((X ~ dbind_tvar) ++ Γ) (open_utyp_wrt_utyp F (utyp_var_f X))) ->
    d_wf_utyp_new Γ (utyp_all_etag ε F).

(** [d_wf_skel_new]: structural wf over [skel]. Admits hole / tophole. *)
Inductive d_wf_skel_new : list atom -> list (atom * dbind) -> skel -> Prop :=
| d_wf_skel_new__unit : forall Ψ Γ,
    d_wf_skel_new Ψ Γ skel_unit
| d_wf_skel_new__var : forall Ψ Γ X,
    List.In X Ψ \/ binds X dbind_tvar Γ ->
    d_wf_skel_new Ψ Γ (skel_var_f X)
| d_wf_skel_new__arrow : forall Ψ Γ R1 R2,
    d_wf_skel_new Ψ Γ R1 ->
    d_wf_skel_new Ψ Γ R2 ->
    d_wf_skel_new Ψ Γ (skel_arrow R1 R2)
| d_wf_skel_new__all_syn : forall L Ψ Γ R,
    (forall X, X `notin` L ->
       d_wf_skel_new (X :: Ψ) Γ (open_skel_wrt_skel R (skel_var_f X))) ->
    d_wf_skel_new Ψ Γ (skel_all_syn R)
| d_wf_skel_new__hole : forall Ψ Γ,
    d_wf_skel_new Ψ Γ skel_hole
| d_wf_skel_new__tophole : forall Γ R,
    d_wf_skel_new nil Γ R ->
    d_wf_skel_new nil Γ (skel_tophole R).

(** ** Plain types under a context. *)
Inductive d_wf_typ : list (atom * dbind) -> typ -> Prop :=
| d_wf_typ__unit : forall Γ,
    d_wf_typ Γ typ_unit
| d_wf_typ__var : forall Γ X,
    binds X dbind_tvar Γ ->
    d_wf_typ Γ (typ_var_f X)
| d_wf_typ__arrow : forall Γ A B,
    d_wf_typ Γ A ->
    d_wf_typ Γ B ->
    d_wf_typ Γ (typ_arrow A B)
| d_wf_typ__all : forall L Γ c A,
    (forall X, X `notin` L ->
       d_wf_typ ((X ~ dbind_tvar) ++ Γ) (open_typ_wrt_typ A (typ_var_f X))) ->
    d_wf_typ Γ (typ_all_col c A).

(** [d_wf_typ] depends only on a type's *skeleton* (variable bindings
    + structure), never on [forall]-colours ([d_wf_typ__all] is
    colour-agnostic). So [syn_color C] and [inh_color C] — same shape,
    different paint — are equi-wf. ([d_wf_typ_recolour] cannot be
    stated as a general [erase]-equality lemma because [d_wf_typ] has
    no rule for [typ_all_etag] / [typ_all_plain]; both colourings only
    produce [typ_all_col], so we relate exactly those.) This is the
    [ctyp]-era replacement for the old [syn_color_wf]. *)
Lemma d_wf_typ_inh_color_syn_color : forall Γ C,
    d_wf_typ Γ (inh_color C) -> d_wf_typ Γ (syn_color C).
Proof.
  intros Γ C H.
  remember (inh_color C) as A eqn:HA. revert C HA.
  induction H; intros C HA.
  - destruct C; simpl in HA; try discriminate. apply d_wf_typ__unit.
  - destruct C; simpl in HA; try discriminate.
    injection HA as HA; subst. apply d_wf_typ__var; assumption.
  - destruct C; simpl in HA; try discriminate.
    injection HA as HA1 HA2.
    apply d_wf_typ__arrow; [ apply IHd_wf_typ1 | apply IHd_wf_typ2 ]; assumption.
  - destruct C; simpl in HA; try discriminate.
    injection HA as Hc HA; subst.
    apply d_wf_typ__all with (L := L `union` dom Γ).
    intros X HX. rewrite <- syn_color_open_var.
    specialize (H0 X ltac:(auto) (open_ctyp_wrt_ctyp C (ctyp_var_f X))).
    apply H0. symmetry. apply inh_color_open_var.
Qed.

Lemma d_wf_typ_syn_color_inh_color : forall Γ C,
    d_wf_typ Γ (syn_color C) -> d_wf_typ Γ (inh_color C).
Proof.
  intros Γ C H.
  remember (syn_color C) as A eqn:HA. revert C HA.
  induction H; intros C HA.
  - destruct C; simpl in HA; try discriminate. apply d_wf_typ__unit.
  - destruct C; simpl in HA; try discriminate.
    injection HA as HA; subst. apply d_wf_typ__var; assumption.
  - destruct C; simpl in HA; try discriminate.
    injection HA as HA1 HA2.
    apply d_wf_typ__arrow; [ apply IHd_wf_typ1 | apply IHd_wf_typ2 ]; assumption.
  - destruct C; simpl in HA; try discriminate.
    injection HA as Hc HA; subst.
    apply d_wf_typ__all with (L := L `union` dom Γ).
    intros X HX. rewrite <- inh_color_open_var.
    specialize (H0 X ltac:(auto) (open_ctyp_wrt_ctyp C (ctyp_var_f X))).
    apply H0. symmetry. apply syn_color_open_var.
Qed.

(** ** Well-formed skeletons. Ψ tracks type variables bound previously in
    this skeleton; cleared at □ and at *.P. We forbid TOPHOLE.HOLE and
    nested TOPHOLE / quantifiers (paper line 1190+). *)
Inductive d_wf_skel :
  list atom -> list (atom * dbind) -> typ -> Prop :=
| d_wf_skel__unit : forall Ψ Γ,
    Ψ ⨟ Γ ⊢ₛₖ typ_unit
| d_wf_skel__var : forall Ψ Γ X,
    List.In X Ψ \/ binds X dbind_tvar Γ ->
    Ψ ⨟ Γ ⊢ₛₖ (typ_var_f X)
| d_wf_skel__arrow : forall Ψ Γ P Q,
    Ψ ⨟ Γ ⊢ₛₖ P ->
    Ψ ⨟ Γ ⊢ₛₖ Q ->
    Ψ ⨟ Γ ⊢ₛₖ (typ_arrow P Q)
| d_wf_skel__all_col : forall L Ψ Γ c P,
    (forall X, X `notin` L ->
       (X :: Ψ) ⨟ Γ ⊢ₛₖ (open_typ_wrt_typ P (typ_var_f X))) ->
    Ψ ⨟ Γ ⊢ₛₖ (typ_all_col c P)
(* d_wf_skel__all_plain dropped post-refactor: typ_all_plain no longer in
   the typ AST. Paper's plain forall (no colour) lives in ctyp, not typ. *)
| d_wf_skel__hole : forall Ψ Γ,
    Ψ ⨟ Γ ⊢ₛₖ typ_hole
| d_wf_skel__tophole : forall Ψ Γ P,
    guarded_skel P ->
    nil ⨟ Γ ⊢ₛₖ P ->
    Ψ ⨟ Γ ⊢ₛₖ (typ_tophole P)
where "Ψ ⨟ Γ ⊢ₛₖ P" := (d_wf_skel Ψ Γ P) : type_scope.

(** ** Well-formedness of tagged types. Each ε must appear exactly once
    (linearity by disjoint append). *)
Inductive d_wf_ttyp :
  list atom -> list (atom * dbind) -> typ -> Prop :=
| d_wf_ttyp__unit : forall Γ,
    nil ⨟ Γ ⊢ₜₜ typ_unit
| d_wf_ttyp__var : forall Γ X,
    binds X dbind_tvar Γ ->
    nil ⨟ Γ ⊢ₜₜ (typ_var_f X)
| d_wf_ttyp__arrow : forall Δ1 Δ2 Γ A B,
    Δ1 ⨟ Γ ⊢ₜₜ A ->
    Δ2 ⨟ Γ ⊢ₜₜ B ->
    list_disjoint Δ1 Δ2 ->
    (Δ1 ++ Δ2) ⨟ Γ ⊢ₜₜ (typ_arrow A B)
| d_wf_ttyp__all : forall L Δ Γ ε A,
    (forall X, X `notin` L ->
       Δ ⨟ ((X ~ dbind_tvar) ++ Γ) ⊢ₜₜ (open_typ_wrt_typ A (typ_var_f X))) ->
    ~ List.In ε Δ ->
    (ε :: Δ) ⨟ Γ ⊢ₜₜ (typ_all_etag ε A)
where "Δ ⨟ Γ ⊢ₜₜ φ" := (d_wf_ttyp Δ Γ φ) : type_scope.

(** ** Well-formedness of unresolved types. The "potential tag δ" (empty or ε)
    is encoded by two ∀ constructors; Δ tracks only the ε-tagged ones. *)
Inductive d_wf_utyp :
  list atom -> list (atom * dbind) -> typ -> Prop :=
| d_wf_utyp__unit : forall Γ,
    d_wf_utyp nil Γ typ_unit
| d_wf_utyp__var : forall Γ X,
    binds X dbind_tvar Γ ->
    d_wf_utyp nil Γ (typ_var_f X)
| d_wf_utyp__arrow : forall Δ1 Δ2 Γ A B,
    d_wf_utyp Δ1 Γ A ->
    d_wf_utyp Δ2 Γ B ->
    list_disjoint Δ1 Δ2 ->
    d_wf_utyp (Δ1 ++ Δ2) Γ (typ_arrow A B)
| d_wf_utyp__tall : forall L Δ Γ ε A,
    (forall X, X `notin` L ->
       d_wf_utyp Δ ((X ~ dbind_tvar) ++ Γ) (open_typ_wrt_typ A (typ_var_f X))) ->
    ~ List.In ε Δ ->
    d_wf_utyp (ε :: Δ) Γ (typ_all_etag ε A)
.
