(** ** Colour discipline — [ctyp] is the colourless / un-decorated type.

    [ctyp] (defined in [def_ott], generated by [ott] + [lngen]) is the
    *colourless* type: [typ]'s shape with all [forall] flavours
    ([typ_all_col], [typ_all_etag]) collapsed to one neutral binder
    [ctyp_all]. It is the "free equivalence class" of coloured types —
    two coloured [typ]s are *convertible* (interchangeable up to colour
    / tag) exactly when they [erase] to the same [ctyp].

    [ctyp] is never used as a term annotation, a context binding, or a
    judgement index — those stay [typ]. It appears in two roles:

    1. *Painting bases* in coloured rules: where the paper writes
       [syn{A}] / [inh{A}] over a meta-symbol [A], the mechanisation
       quantifies one base [C : ctyp] and writes [syn_color C] /
       [inh_color C]. Different-colour occurrences thus share their
       shape (the base [C]).

    2. *Plain world*: the natural home for the paper's un-decorated
       (no colour, no tag) [forall] — used in skeleton wf, refinement
       output, and the plain pattern judgements. Post-refactor the
       old [typ_all_plain] is gone; its role is split between
       [ctyp_all] (for genuinely-plain world) and
       [typ_all_col colour_syn] (for paper's [syn{∀α.}T] untagged
       synthesised forall in coloured-world contexts).

    Here we define only [syn_color] / [inh_color] / [erase] and their
    commutation lemmas — [ctyp]'s locally-nameless infrastructure
    ([open_ctyp_wrt_ctyp], [ftvar_in_ctyp], [subst_ctyp_in_ctyp]) lives
    in [def_ott] / [prop_ln]. *)

(** [syn_color] / [inh_color]: paint a colourless [ctyp]
    all-synthesised / all-inherited. The neutral binder [ctyp_all]
    becomes [typ_all_col colour_syn] / [typ_all_col colour_inh]. *)
Fixpoint syn_color (C : ctyp) : typ :=
  match C with
  | ctyp_unit => typ_unit
  | ctyp_var_b n => typ_var_b n
  | ctyp_var_f X => typ_var_f X
  | ctyp_arrow C1 C2 => typ_arrow (syn_color C1) (syn_color C2)
  | ctyp_all C0 => typ_all_col colour_syn (syn_color C0)
  | ctyp_hole => typ_hole
  | ctyp_tophole C0 => typ_tophole (syn_color C0)
  end.

Fixpoint inh_color (C : ctyp) : typ :=
  match C with
  | ctyp_unit => typ_unit
  | ctyp_var_b n => typ_var_b n
  | ctyp_var_f X => typ_var_f X
  | ctyp_arrow C1 C2 => typ_arrow (inh_color C1) (inh_color C2)
  | ctyp_all C0 => typ_all_col colour_inh (inh_color C0)
  | ctyp_hole => typ_hole
  | ctyp_tophole C0 => typ_tophole (inh_color C0)
  end.

(** [erase]: forget all colour/tag information, projecting a coloured
    [typ] onto its [ctyp] equivalence class. Post-refactor the
    [typ_all_plain] case is gone (constructor removed from [typ]). The
    round-trips [erase (syn_color C) = C = erase (inh_color C)] are
    proved in the proof layer. *)
Fixpoint erase (A : typ) : ctyp :=
  match A with
  | typ_unit => ctyp_unit
  | typ_var_b n => ctyp_var_b n
  | typ_var_f X => ctyp_var_f X
  | typ_arrow A1 A2 => ctyp_arrow (erase A1) (erase A2)
  | typ_all_col _ A0 => ctyp_all (erase A0)
  | typ_all_etag _ A0 => ctyp_all (erase A0)
  | typ_hole => ctyp_hole
  | typ_tophole A0 => ctyp_tophole (erase A0)
  end.

