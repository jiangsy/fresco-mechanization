Lemma e_assign_unify_consis_out_ftvar :
  (forall S0 Θ0 Ξ α P S1 Θ1,
     {{ S0 ↝ S1 ⊨ Θ0 ⊲[ Ξ ] α ≔ P ⊣ Θ1 }}e -> True) /\
