    exists S1'. split; [ exact HS1 | ].
    apply e_unify__skip_other; [ | exact Hd' ].
    destruct Hb as [-> | [[A ->] | [Qb ->]]]; simpl.
    + left; reflexivity.
    + right; left; eexists; reflexivity.
    + right; right; eexists; reflexivity.
  (* ==================== consis ==================== *)
  - (* Ghost *)
    intros Δ1 Δ2 S Θ0 P0 Hemp Δ1' Δ2' S0' HΔ1 HΔ2 Heq. simpl.
