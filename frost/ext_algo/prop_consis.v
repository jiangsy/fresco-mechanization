    (fun S0 Θ0 Ξ α P S1 Θ1 _ => True)
    (fun S0 Θ0 α β S1 Θ1 _ => True)
    (fun Δ1 Δ2 S0 Θ0 P0 P Q S1 Θ1 _ =>
       uniq Θ0 ->
       ftvar_in_aenv Θ0 ∪ ftvar_in_pskl P0 ∪ ftvar_in_pskl P
         ∪ Δ1 ∪ Δ2 [<=] S0 ->
       ftvar_in_pskl Q [<=] S1));
