    exists S1'. split; [ exact HS1 | apply e_assign__skip_tm_skl; exact Hd' ].
  (* ==================== unify ==================== *)
  - (* Flex-Flex-Id *)
    intros S Θ0 α Hflex S0' Heq. simpl.
