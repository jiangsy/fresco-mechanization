     {{ S0 ↝ S1 ⊨ Θ0 ⊢[ Δ1 | Δ2 | P0 ] P ∼ Q ⊣ Θ1 }}e ->
     uniq Θ0 ->
     ftvar_in_aenv Θ0 ∪ ftvar_in_pskl P0 ∪ ftvar_in_pskl P
       ∪ Δ1 ∪ Δ2 [<=] S0 ->
     ftvar_in_pskl Q [<=] S1).
